import { ChildProcess, spawn } from 'child_process'
import fs from 'fs'
import net from 'net'
import path from 'path'
import { getAppDataDir } from './app-paths'
import { getProjectAssetsPath } from './app-state'
import { getCurrentDir, isDev } from './config'
import { logger, writeLog } from './logger'
import { getAuthToken, getBackendUrl, getPythonPath } from './python-backend'

type ComfyUIState = 'stopped' | 'starting' | 'running' | 'error'

export interface ComfyUIStatus {
  state: ComfyUIState
  url?: string
  port?: number
  error?: string
  ltxDataPath: string
  ltxModelsPath: string
  inputPath: string
  outputPath: string
  userPath: string
}

interface ComfyUIPaths {
  rootPath: string
  ltxVideoCustomNodePath: string
  ltxDataPath: string
  ltxModelsPath: string
  inputPath: string
  outputPath: string
  tempPath: string
  userPath: string
  extraModelPathsConfig: string
}

let comfyProcess: ChildProcess | null = null
let comfyState: ComfyUIState = 'stopped'
let comfyUrl: string | undefined
let comfyPort: number | undefined
let comfyError: string | undefined
let startPromise: Promise<ComfyUIStatus> | null = null
let lastPaths: ComfyUIPaths | null = null

const START_PORT = 8188
const START_TIMEOUT_MS = 300_000

function ensureDir(dir: string): void {
  fs.mkdirSync(dir, { recursive: true })
}

function getComfyUIRoot(): string {
  if (isDev) {
    return path.join(getCurrentDir(), 'ComfyUI')
  }
  return path.join(process.resourcesPath, 'ComfyUI')
}

function getDefaultModelsPath(): string {
  const modelsPath = path.join(getAppDataDir(), 'models')
  ensureDir(modelsPath)
  return modelsPath
}

function getLtxVideoSourcePath(): string {
  return path.join(getCurrentDir(), 'ComfyUI-LTXVideo')
}

function copyLtxVideoCustomNode(sourcePath: string, targetPath: string): void {
  fs.cpSync(sourcePath, targetPath, {
    recursive: true,
    force: true,
    filter: (src) => {
      const relativePath = path.relative(sourcePath, src)
      if (!relativePath) return true
      return !relativePath.split(path.sep).includes('.git')
    },
  })
}

function ensureLtxVideoCustomNode(rootPath: string): string {
  const targetPath = path.join(rootPath, 'custom_nodes', 'ComfyUI-LTXVideo')
  const sourcePath = getLtxVideoSourcePath()

  ensureDir(path.dirname(targetPath))
  if (fs.existsSync(sourcePath) && path.resolve(sourcePath) !== path.resolve(targetPath)) {
    copyLtxVideoCustomNode(sourcePath, targetPath)
  }

  if (!fs.existsSync(path.join(targetPath, '__init__.py'))) {
    throw new Error(
      `ComfyUI-LTXVideo was not found. Expected it at ${targetPath}` +
        (fs.existsSync(sourcePath) ? '' : ` or ${sourcePath}`),
    )
  }

  return targetPath
}

async function getEffectiveModelsPath(): Promise<string> {
  const fallback = getDefaultModelsPath()
  const backendUrl = getBackendUrl()
  if (!backendUrl) {
    return fallback
  }

  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), 1500)
  try {
    const headers: Record<string, string> = {}
    const token = getAuthToken()
    if (token) headers.Authorization = `Bearer ${token}`
    const response = await fetch(`${backendUrl}/api/settings`, {
      headers,
      signal: controller.signal,
    })
    if (!response.ok) {
      return fallback
    }
    const settings = await response.json() as { modelsDir?: unknown }
    const configured = typeof settings.modelsDir === 'string' ? settings.modelsDir.trim() : ''
    if (configured) {
      ensureDir(configured)
      return path.resolve(configured)
    }
  } catch {
    return fallback
  } finally {
    clearTimeout(timeout)
  }

  return fallback
}

function yamlString(value: string): string {
  return JSON.stringify(value.replace(/\\/g, '/'))
}

